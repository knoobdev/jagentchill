// Lists the display strings of the effect, filter, transition and clip-animation catalogues — names, categories, parameter labels and
// option labels — in `src/editor/fx/strings.gen.ts`, so that the locale tables carry them (the screens translate a
// catalogue entry by its English text). Run after the catalogue changes, then `node scripts/gen-locale.mjs`.
// Usage: node scripts/gen-fx-strings.mjs
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { EASING_LABELS, FADE_SHAPE_LABELS, fxCategories, optionLabel, paramLabel } from "../../../packages/app-core/src/editor/fx.ts";
import { CLIP_ANIMATION_GROUPS, clipAnimationsOf, EFFECT_DEFINITIONS, FILTER_DEFINITIONS, TRANSITION_DEFINITIONS } from "../../../packages/editor-core/src/index.ts";

const all = [...EFFECT_DEFINITIONS, ...FILTER_DEFINITIONS, ...TRANSITION_DEFINITIONS];
const strings = new Set();
for (const kind of ["effect", "filter", "transition"]) for (const category of fxCategories(kind)) strings.add(category);
for (const definition of all) {
  strings.add(definition.name);
  for (const param of definition.params) { strings.add(paramLabel(param.key)); for (const option of param.options ?? []) strings.add(optionLabel(option)); }
}
for (const group of CLIP_ANIMATION_GROUPS) for (const row of clipAnimationsOf(group)) strings.add(row.name);
for (const label of [...Object.values(EASING_LABELS), ...Object.values(FADE_SHAPE_LABELS)]) strings.add(label);
const sorted = [...strings].sort((a, b) => a.localeCompare(b));
writeFileSync(join(new URL("..", import.meta.url).pathname, "src/editor/fx/strings.gen.ts"),
  `// Generated by scripts/gen-fx-strings.mjs from the catalogues of @jagentchill/content — do not edit.\n\n/** The display strings of the effect, filter, transition and clip-animation catalogues: what the locale tables translate. */\nexport const FX_STRINGS: readonly { label: string }[] = [\n${sorted.map((text) => `  { label: ${JSON.stringify(text)} },`).join("\n")}\n];\n`);
console.log(`${sorted.length} strings`);
