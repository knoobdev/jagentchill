import { execFileSync } from 'node:child_process';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { chromium } from 'playwright';

const base = 'http://127.0.0.1:8097';
const dir = join('.dev', `run-w18c-export-stuck-${Date.now()}`);
const shots = '.refs/apply/briefs';
mkdirSync(dir);
mkdirSync(shots, { recursive: true });
const media = (name) => join(dir, name);
const ffmpeg = (...args) => execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...args]);
console.log('RUN_DIR', dir);
ffmpeg('-f', 'lavfi', '-i', 'color=c=red:s=640x360:r=30:d=2', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', media('stall-red.mp4'));
ffmpeg('-f', 'lavfi', '-i', 'color=c=blue:s=640x360:r=30:d=3', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', media('stall-blue.mp4'));
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true, colorScheme: 'light' });
await context.addInitScript(() => {
  window.showSaveFilePicker = async ({ suggestedName }) => {
    const root = await navigator.storage.getDirectory();
    const folder = await root.getDirectoryHandle('w18a-picked', { create: true });
    const handle = await folder.getFileHandle(suggestedName, { create: true });
    const createWritable = handle.createWritable.bind(handle);
    handle.createWritable = async (...args) => {
      const writable = await createWritable(...args);
      writable.close = () => new Promise(() => undefined);
      return writable;
    };
    return handle;
  };
});
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(String(error)));
const tid = (name) => page.getByTestId(name).filter({ visible: true }).first();
const button = (name) => page.getByRole('button', { name, exact: true }).filter({ visible: true }).first();
await page.goto(`${base}/projects`, { waitUntil: 'networkidle', timeout: 180_000 });
await button('Create your first project').click({ timeout: 90_000 });
await page.waitForURL(/\/editor\/[0-9a-f-]{36}$/);
await tid('timeline').waitFor({ timeout: 60_000 });
const [chooser] = await Promise.all([page.waitForEvent('filechooser'), tid('media-dropzone').click()]);
await chooser.setFiles([media('stall-red.mp4'), media('stall-blue.mp4')]);
for (const name of ['stall-red.mp4', 'stall-blue.mp4']) await tid(`label-${name}`).waitFor({ timeout: 60_000 });
await tid('thumb-stall-red.mp4').dblclick();
await page.waitForFunction(() => document.querySelectorAll('[data-testid="track-main-video"] [data-testid^="clip-"]').length >= 1);
await tid('thumb-stall-blue.mp4').dblclick();
await page.waitForFunction(() => document.querySelectorAll('[data-testid="track-main-video"] [data-testid^="clip-"]').length >= 2);
await page.getByTestId('save-state').getByText('Saved', { exact: true }).waitFor({ timeout: 20_000 });
await tid('open-export').click();
await tid('export-dialog').waitFor();
await tid('export-start').click();
await page.waitForFunction(() => document.querySelector('[data-testid="export-stage"]')?.textContent?.trim() === 'Finalising', null, { timeout: 180_000 });
await page.waitForFunction(() => Number(document.querySelector('[data-testid="export-progress"]')?.textContent?.match(/(\d+) of (\d+) frames/)?.[1]) === Number(document.querySelector('[data-testid="export-progress"]')?.textContent?.match(/(\d+) of (\d+) frames/)?.[2]), null, { timeout: 10_000 });
const pause = tid('export-pause');
if (!(await pause.isDisabled())) throw new Error('Pause was not disabled after all frames were done');
if (!(await tid('export-pause-reason').isVisible())) throw new Error('Pause reason was not visible');
await page.screenshot({ path: `${shots}/w18a-export-finalising-pause-disabled.png` });
console.log('FINALISING', JSON.stringify({ progress: await tid('export-progress').innerText(), pauseDisabled: await pause.isDisabled(), pauseReason: await tid('export-pause-reason').innerText() }));
if (process.argv[2] === 'timeout') {
  const started = performance.now();
  await page.waitForTimeout(62_000);
  await page.goto(`${base}/exports/history`, { waitUntil: 'networkidle', timeout: 30_000 });
  await tid('export-history').waitFor({ timeout: 10_000 });
  await page.getByTestId(/^export-row-state-/).getByText('Failed', { exact: true }).waitFor({ timeout: 5_000 });
  await page.getByTestId(/^export-row-open-/).first().click();
  const error = page.getByTestId('export-error');
  await error.getByText('Export finalising did not make progress for 60 seconds. Retry the export.', { exact: true }).waitFor({ timeout: 3_000 });
  await tid('failure-retry').waitFor({ timeout: 2_000 });
  const timeoutMs = performance.now() - started;
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${shots}/w18a-export-finalising-timeout.png` });
  console.log('TIMEOUT', JSON.stringify({ elapsedAfterFinalisingMs: Math.round(timeoutMs), error: await error.innerText(), retryVisible: await tid('failure-retry').isVisible() }));
} else {
  await tid('export-cancel').click();
  await page.getByText('Cancel export? The partial file is deleted.', { exact: true }).waitFor({ timeout: 2_000 });
  const confirm = page.getByRole('button', { name: 'Cancel export', exact: true }).filter({ visible: true });
  console.log('CANCEL_CONFIRM', JSON.stringify({ buttons: await confirm.allTextContents(), dialogs: await page.locator('[role="dialog"]').allInnerTexts(), alertdialogs: await page.locator('[role="alertdialog"]').allInnerTexts() }));
  await page.screenshot({ path: `${shots}/w18a-export-cancel-confirmation.png` });
  const confirmation = page.getByTestId('modal').last().getByRole('button', { name: 'Cancel export', exact: true });
  const confirmStarted = performance.now();
  await confirmation.click({ timeout: 2_000 });
  await page.getByText('Cancel export? The partial file is deleted.', { exact: true }).waitFor({ state: 'hidden', timeout: 2_000 });
  await page.waitForTimeout(500);
  await page.goto(`${base}/exports/history`, { waitUntil: 'networkidle', timeout: 30_000 });
  await tid('export-history').waitFor({ timeout: 10_000 });
  await page.getByTestId(/^export-row-state-/).getByText('Cancelled', { exact: true }).waitFor({ timeout: 10_000 });
  const cancelMs = performance.now() - confirmStarted;
  await page.getByTestId(/^export-row-open-/).first().click();
  await page.getByTestId('job-dialog').getByText('This export was cancelled. The partial file was deleted.').waitFor({ timeout: 2_000 });
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${shots}/w18a-export-finalising-cancelled.png` });
  console.log('CANCELLED', JSON.stringify({ cancelMs: Math.round(cancelMs), cancelledText: true }));
  if (cancelMs >= 2_000) throw new Error(`Cancel took ${Math.round(cancelMs)} ms`);
}
if (errors.length) throw new Error(errors.join('\n'));
await browser.close();
