#!/usr/bin/env python3
"""Generates packages/ui/src/icons.gen.ts from the icon sprite of docs/design/jagentchill-ui.html and the project-owned icons of packages/ui/icons/project.svg."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "docs/design/jagentchill-ui.html").read_text() + (root / "packages/ui/icons/project.svg").read_text()
icons = {}
for m in re.finditer(r'<symbol id="([^"]+)"([^>]*)>(.*?)</symbol>', html, re.S):
    name, attrs, body = m.group(1), m.group(2), re.sub(r"\s+", " ", m.group(3)).strip()
    box = re.search(r'viewBox="([^"]+)"', attrs)
    icons[name] = {"viewBox": box.group(1) if box else "0 0 16 16", "attrs": re.sub(r'\s*viewBox="[^"]+"', "", attrs).strip(), "body": body}
out = "// Generated by scripts/gen-icons.py from docs/design/jagentchill-ui.html and packages/ui/icons/project.svg — do not edit.\n"
out += "export const ICONS = " + json.dumps(icons, indent=1, ensure_ascii=False) + " as const;\n"
out += "export type IconName = keyof typeof ICONS;\n"
(root / "packages/ui/src/icons.gen.ts").write_text(out)
print(len(icons), "icons")
