import assert from "node:assert/strict";
import { test } from "node:test";
import { generatedAssetName } from "../src/generation/tools.ts";

test("generated asset name overrides keep the real media extension", () => {
  assert.equal(generatedAssetName(undefined, "Welcome to the film.mp3"), "Welcome to the film.mp3");
  assert.equal(generatedAssetName("Bài 04 · VI · Xin chào", "Welcome.mp3"), "Bài 04 · VI · Xin chào.mp3");
  assert.equal(generatedAssetName("Bài 05 · VI · Xin chào.", "Welcome.wav"), "Bài 05 · VI · Xin chào.wav");
  assert.equal(generatedAssetName("voice.take words", "Welcome.wav"), "voice.take words.wav");
  assert.equal(generatedAssetName("voice.mp3", "Welcome.wav"), "voice.wav", "the generated bytes determine the extension");
});
