// Renders the cover and the preview of every bundled template with the product itself, in a headless browser:
// each starter (as `packages/editor-core/src/template/bundled.ts` builds it) is written as a `.jctpl` package, imported
// in the app, used ("Use template"), filled with its demo media through "Add clips", and exported to MP4 by the app's
// own export. The cover is the frame of that export at the starter's cover time; the preview is the export scaled to
// 720 px on its long side. Nothing is drawn outside the app: what a card shows is what the template renders.
//
// Needs a production web build of the app being served, and the demo media (`make-demo-media.mjs`).
// Usage: node packages/content/scripts/render-template-covers.mjs [base-url] [template-id …]
// Output: packages/content/templates/<id>/{cover.jpg,preview.mp4}, copied to apps/app/public/templates/<id>/.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium } from "playwright";
import { template } from "../../editor-core/src/index.ts";
import { FILE_FORMATS, memorySink, writePackage } from "../../storage/src/index.ts";

const root = join(import.meta.dirname, "../../..");
const content = join(root, "packages/content/templates"), served = join(root, "apps/app/public/templates"), demo = join(content, "demo");
const args = process.argv.slice(2);
const base = args[0]?.startsWith("http") ? args.shift() : "http://localhost:8094";
const starters = template.bundledTemplates().filter((entry) => args.length === 0 || args.includes(entry.manifest.id));
// The app keeps the covers and previews in Cache Storage under a name that carries their hash: new files, a new name.
const writeVersion = () => {
  const hash = createHash("sha256");
  for (const { manifest } of template.bundledTemplates()) for (const name of ["cover.jpg", "preview.mp4"]) { hash.update(`${manifest.id}/${name}\n`); hash.update(readFileSync(join(served, manifest.id, name))); }
  writeFileSync(join(root, "apps/app/src/templates/covers.gen.ts"), `// Generated by packages/content/scripts/render-template-covers.mjs — do not edit.\n/** The hash of the shipped covers and previews of the starter templates: the app's kept copies are named by it. */\nexport const COVERS_VERSION = "${hash.digest("hex").slice(0, 16)}";\n`);
};
// `--version-only` renders nothing: it only writes the hash of the files that are there.
if (args.includes("--version-only")) { writeVersion(); process.exit(0); }
const ffmpeg = (...list) => execFileSync("ffmpeg", ["-loglevel", "error", "-y", ...list]);
const nameOf = (id) => `cover ${id}`;
// Everything that makes a temporary file or a process starts inside the try: a failure leaves nothing behind.
let work = null, browser = null, failed = 0;
const cleanUp = () => { if (work) rmSync(work, { recursive: true, force: true }); work = null; };
process.on("SIGTERM", () => { cleanUp(); process.exit(143); });
try {
  work = mkdtempSync(join(tmpdir(), "jagentchill-covers-"));
  // One package per starter, under an id and a name of its own so that it never meets the starter of the same build.
  for (const { manifest, snapshot } of starters) {
    const id = `cover-${manifest.id}`, sink = memorySink();
    const project = { ...snapshot, metadata: { ...snapshot.metadata, id, name: nameOf(manifest.id) }, template: { ...snapshot.template, templateId: id } };
    await writePackage({ ...sink, close: async () => undefined, abort: async () => undefined }, { format: "jagentchill-template", formatVersion: FILE_FORMATS.template.formatVersion, appVersion: "0.0.0", ...manifest, id, name: nameOf(manifest.id), thumbnail: null, preview: null },
      [{ path: "project.json", data: new TextEncoder().encode(JSON.stringify(project)) }]);
    writeFileSync(join(work, `${manifest.id}.jctpl`), sink.bytes());
  }
  browser = await chromium.launch({ args: ["--autoplay-policy=no-user-gesture-required"] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "light", acceptDownloads: true });
  // The save dialog of a headless browser: a real file handle in the private file system, under `picked/`.
  await context.addInitScript(() => {
    window.showSaveFilePicker = async (options) => { const folder = await (await navigator.storage.getDirectory()).getDirectoryHandle("picked", { create: true }); return folder.getFileHandle(options.suggestedName, { create: true }); };
    delete window.showDirectoryPicker;
  });
  const page = await context.newPage();
  page.on("pageerror", (error) => console.log("pageerror:", error.message.slice(0, 300)));
  const visible = (locator) => locator.filter({ visible: true }).first();
  const tid = (id) => visible(page.getByTestId(id));
  const pick = async (trigger, files) => { const [chooser] = await Promise.all([page.waitForEvent("filechooser"), trigger.click()]); await chooser.setFiles(files); };
  const gallery = async () => {
    await page.goto(`${base}/library/templates`, { waitUntil: "networkidle", timeout: 240_000 });
    await tid("templates-tab").waitFor({ timeout: 90_000 });
    await visible(page.getByRole("tab", { name: /My templates/ })).click();
  };
  await gallery();
  await pick(tid("templates-import"), starters.map(({ manifest }) => join(work, `${manifest.id}.jctpl`)));
  await page.locator('[data-testid="template-card"][data-source="mine"]').nth(starters.length - 1).waitFor({ timeout: 120_000 });

  for (const { manifest } of starters) {
    const id = manifest.id, { media, coverAt } = template.bundledTemplateDemo(id);
    try {
      const started = Date.now();
      await gallery();
      const card = visible(page.locator(`[data-testid="template-card"][data-name="${nameOf(id)}"]`));
      await card.getByTestId("template-open").click();
      await tid("template-use").click();
      await tid("template-editor").waitFor({ timeout: 90_000 });
      // The n-th file fills the n-th slot: a clip for a slot that takes video, a still for one that takes images only.
      const files = manifest.slots.map((slot, index) => { const name = media[index]; return join(demo, name.includes(".") ? name : `${name}.${slot.accepts === "image" ? "jpg" : "mp4"}`); });
      await pick(tid("template-fill"), files);
      for (let tries = 0; ; tries++) {
        if ((await page.locator('[data-testid="template-slot"][data-filled="true"]').filter({ visible: true }).count()) === manifest.slots.length) break;
        if (tries > 300) throw new Error(`the slots were not filled: ${(await page.locator("body").innerText()).replace(/\s+/g, " ").slice(-200)}`);
        await page.waitForTimeout(200);
      }
      await visible(page.getByTestId("save-state").getByText("Saved", { exact: true })).waitFor({ timeout: 60_000 });
      await tid("open-export").click();
      await tid("export-dialog").waitFor();
      await page.waitForTimeout(1000);
      await tid("export-start").click();
      await Promise.race([tid("export-done").waitFor({ timeout: 900_000 }), tid("export-error").waitFor({ timeout: 900_000 })]);
      if (!(await page.getByTestId("export-done").count())) throw new Error(`the export failed: ${(await tid("export-dialog").innerText()).replace(/\s+/g, " ").slice(-300)}`);
      const name = (await tid("export-done-name").innerText()).trim();
      const bytes = await page.evaluate(async (fileName) => {
        const folder = await (await navigator.storage.getDirectory()).getDirectoryHandle("picked"), data = new Uint8Array(await (await (await folder.getFileHandle(fileName)).getFile()).arrayBuffer());
        let text = ""; for (let at = 0; at < data.length; at += 0x8000) text += String.fromCharCode(...data.subarray(at, at + 0x8000));
        await folder.removeEntry(fileName);
        return btoa(text);
      }, name);
      const exported = join(work, `${id}.mp4`);
      writeFileSync(exported, Buffer.from(bytes, "base64"));

      const out = join(content, id), fit = manifest.canvas.width >= manifest.canvas.height ? "720:-2" : "-2:720";
      mkdirSync(out, { recursive: true });
      ffmpeg("-ss", String(coverAt), "-i", exported, "-frames:v", "1", "-vf", `scale=${fit}:flags=lanczos`, "-q:v", "3", join(out, "cover.jpg"));
      ffmpeg("-i", exported, "-vf", `scale=${fit}:flags=lanczos`, "-an", "-c:v", "libx264", "-preset", "slow", "-crf", "30", "-pix_fmt", "yuv420p", "-movflags", "+faststart", join(out, "preview.mp4"));
      mkdirSync(join(served, id), { recursive: true });
      for (const file of ["cover.jpg", "preview.mp4"]) copyFileSync(join(out, file), join(served, id, file));
      const seconds = Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", exported]).toString());
      console.log(`ok   ${id}: export ${seconds.toFixed(2)} s (template ${(manifest.duration / 120_000).toFixed(0)} s), cover ${(statSync(join(out, "cover.jpg")).size / 1024).toFixed(0)} KB, preview ${(statSync(join(out, "preview.mp4")).size / 1024).toFixed(0)} KB, ${((Date.now() - started) / 1000).toFixed(0)} s`);
    } catch (error) {
      failed++;
      console.log(`FAIL ${id}: ${String(error).split("\n")[0]}`);
      await page.screenshot({ path: join(root, `.dev/shots/w2-templates/render-failure-${id}.png`) }).catch(() => undefined);
    }
  }
} finally {
  await browser?.close().catch(() => undefined);
  cleanUp();
}
if (!existsSync(join(served, starters[0].manifest.id, "cover.jpg"))) failed++;
if (failed === 0) writeVersion();
console.log(failed === 0 ? `rendered ${starters.length} templates` : `FAILED: ${failed}`);
process.exit(failed === 0 ? 0 : 1);
