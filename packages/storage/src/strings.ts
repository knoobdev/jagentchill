export type StorageLocale = "en" | "vi" | "ja";
export const STORAGE_STRINGS: Record<StorageLocale, Table> = { en, vi, ja };
/** A storage string with its `{placeholders}` filled in. */
export function storageString(key: StorageStringKey, values: Record<string, string | number> = {}, locale: StorageLocale = "en"): string {
  return STORAGE_STRINGS[locale][key].replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
}
